-- Entrada tardia opt-in. Mundos sem configuração mantêm o comportamento anterior.
begin;
create table if not exists public.kw_cozy_late_join_config (
  world_id uuid primary key references public.worlds(id) on delete cascade,
  deadline timestamptz not null
);
create table if not exists public.kw_cozy_late_join_slots (
  world_player_id uuid primary key references public.world_players(id) on delete cascade,
  world_id uuid not null references public.worlds(id) on delete cascade,
  q integer not null check(q between -40 and 40),
  r integer not null check(r between -40 and 40),
  claimed_by uuid references public.users(id),
  claimed_at timestamptz
);
alter table public.kw_cozy_late_join_config enable row level security;
alter table public.kw_cozy_late_join_slots enable row level security;
revoke all on public.kw_cozy_late_join_config, public.kw_cozy_late_join_slots from public, anon, authenticated;
grant select, insert, update, delete on public.kw_cozy_late_join_config, public.kw_cozy_late_join_slots to service_role;

-- The trusted caller supplies the exact initial position generated by the game engine.
-- The world lock is the same one used by joins and commits.
create or replace function public.kw_cozy_reserve_late_slot(p_world_id uuid,p_player_id uuid,p_q integer,p_r integer)
returns void language plpgsql security definer set search_path=public,pg_temp as $$
declare w public.worlds%rowtype; shared jsonb; coord text:=p_q::text||','||p_r::text;
begin
 select * into w from public.worlds where id=p_world_id for update;
 if not found or w.rules_version<>2 or w.status<>'open' then raise exception 'COZY_WORLD_CLOSED'; end if;
 if p_q not between -40 and 40 or p_r not between -40 and 40 then raise exception 'COZY_INVALID_SLOT'; end if;
 if not exists(select 1 from public.world_players where id=p_player_id and world_id=w.id and is_ai=true and status='alive') then raise exception 'COZY_INVALID_SLOT'; end if;
 if exists(select 1 from public.kw_cozy_player_states where world_player_id=p_player_id) or exists(select 1 from public.kw_cozy_commands where world_player_id=p_player_id) then raise exception 'COZY_INVALID_SLOT'; end if;
 select state_json into shared from public.kw_cozy_world_states where world_id=w.id for update;
 shared:=coalesce(shared,'{"version":2,"claims":{},"deposits":{},"alliances":[],"support":[]}'::jsonb);
 if shared->'claims' ? coord or shared->'territories' ? coord or shared->'independentCities' ? coord or shared::text like '%'||p_player_id::text||'%' then raise exception 'COZY_SLOT_OCCUPIED'; end if;
 shared:=jsonb_set(shared,array['claims',coord],jsonb_build_object('playerId',p_player_id::text,'cityId',p_player_id::text||':capital','name','Reino disponível','reservedSlot',true),true);
 insert into public.kw_cozy_world_states(world_id,state_json,revision) values(w.id,shared,0)
 on conflict(world_id) do update set state_json=excluded.state_json,revision=public.kw_cozy_world_states.revision+1,updated_at=now();
 insert into public.kw_cozy_late_join_slots(world_player_id,world_id,q,r) values(p_player_id,w.id,p_q,p_r);
end $$;
revoke all on function public.kw_cozy_reserve_late_slot(uuid,uuid,integer,integer) from public,anon,authenticated;
grant execute on function public.kw_cozy_reserve_late_slot(uuid,uuid,integer,integer) to service_role;

-- Preserve the prior join implementation for open worlds and existing members.
do $$ begin
 if to_regprocedure('public.kw_cozy_join_before_late(uuid,uuid,text)') is null then
  alter function public.kw_cozy_join(uuid,uuid,text) rename to kw_cozy_join_before_late;
 end if;
end $$;
revoke all on function public.kw_cozy_join_before_late(uuid,uuid,text) from public, anon, authenticated;
grant execute on function public.kw_cozy_join_before_late(uuid,uuid,text) to service_role;

create or replace function public.kw_cozy_join(p_world_id uuid, p_user_id uuid, p_join_code text default null)
returns uuid language plpgsql security definer set search_path=public,pg_temp as $$
declare
 w public.worlds%rowtype;
 player_id uuid;
 cutoff timestamptz;
begin
 select * into w from public.worlds where id=p_world_id for update;
 if not found or w.rules_version<>2 then raise exception 'COZY_WORLD_NOT_FOUND'; end if;
 select id into player_id from public.world_players where world_id=w.id and user_id=p_user_id;
 if found then return player_id; end if;
 if w.status='open' then return public.kw_cozy_join_before_late(p_world_id,p_user_id,p_join_code); end if;
 if w.status<>'running' then raise exception 'COZY_JOINS_CLOSED'; end if;
 if p_join_code is null or w.join_code is null or upper(trim(p_join_code))<>upper(w.join_code::text) then raise exception 'COZY_INVITE_REQUIRED'; end if;
 if not exists(select 1 from public.users u where id=p_user_id and coalesce(to_jsonb(u)->>'account_status','active')='active' and to_jsonb(u)->>'deletion_requested_at' is null) then raise exception 'COZY_ACCOUNT_UNAVAILABLE'; end if;
 select deadline into cutoff from public.kw_cozy_late_join_config where world_id=w.id;
 if cutoff is null or clock_timestamp()>=cutoff or cutoff<=coalesce(w.runtime_anchor_started_at,w.starts_at) then raise exception 'COZY_JOINS_CLOSED'; end if;
 select slot.world_player_id into player_id
 from public.kw_cozy_late_join_slots slot
 join public.world_players npc on npc.id=slot.world_player_id and npc.world_id=slot.world_id
 where slot.world_id=w.id and slot.claimed_by is null and npc.is_ai=true
   and npc.status='alive'
   and not exists(select 1 from public.kw_cozy_player_states ps where ps.world_player_id=npc.id)
   and not exists(select 1 from public.kw_cozy_commands cmd where cmd.world_player_id=npc.id)
   and exists(select 1 from public.kw_cozy_world_states ws where ws.world_id=w.id
     and ws.state_json->'claims'->(slot.q::text||','||slot.r::text)->>'playerId'=npc.id::text
     and ws.state_json->'claims'->(slot.q::text||','||slot.r::text)->>'cityId'=npc.id::text||':capital'
     and ws.state_json->'claims'->(slot.q::text||','||slot.r::text)->'reservedSlot'='true'::jsonb
     and (jsonb_set(ws.state_json,'{claims}',(ws.state_json->'claims')-(slot.q::text||','||slot.r::text)))::text not like '%'||npc.id::text||'%')
 order by slot.world_player_id limit 1 for update of slot,npc;
 if player_id is null then raise exception 'COZY_NO_LATE_SLOT'; end if;
 update public.world_players set user_id=p_user_id,is_ai=false,joined_at=clock_timestamp() where id=player_id;
 update public.kw_cozy_late_join_slots set claimed_by=p_user_id,claimed_at=clock_timestamp() where world_player_id=player_id;
 return player_id;
end $$;
revoke all on function public.kw_cozy_join(uuid,uuid,text) from public, anon, authenticated;
grant execute on function public.kw_cozy_join(uuid,uuid,text) to service_role;
commit;
