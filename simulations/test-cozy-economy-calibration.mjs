import assert from 'node:assert/strict';
import {loadCozyEngine} from './lib/load-cozy-engine.mjs';
const E=loadCozyEngine(),P=loadCozyEngine('progression'),at=1800000000000;
const world={id:'calibration',mode:'express',economyVersion:2,influenceVersion:2,status:'running',startsAt:at};
const state=E.createCozyState(world,'p','Player',at),shared=E.createCozyShared(world);
const fresh=E.getCozyComputed(state,shared,world,at);
assert.equal(state.progression.balance.militaryDivisor,75);
const old=structuredClone(state);delete old.progression.balance.materialsProductionMultiplier;delete old.progression.balance.suppliesProductionMultiplier;old.progression.balance.militaryDivisor=90;
const legacy=E.getCozyComputed(old,shared,world,at);
assert.equal(fresh.productionPerDay.materials,legacy.productionPerDay.materials,'Construction income is unchanged');
assert.equal(fresh.productionPerDay.supplies*4,legacy.productionPerDay.supplies,'New supplies rate is separate from materials');
const pinned=E.createCozyShared(world);assert.deepEqual(P.bindWorldBalance(pinned,[old],true),old.progression.balance,'An existing Express world retains its rates and military curve');
const normalWorld={...world,mode:'classic'},normal=E.createCozyState(normalWorld,'p','Player',at);
assert.equal(normal.progression.balance.militaryDivisor,90);assert.equal(normal.progression.balance.materialsProductionMultiplier,undefined);
// Baseline troops create no points; progress and combat losses are reflected immediately.
assert.equal(fresh.influence.total,0);
const developed=structuredClone(state);developed.army.militia+=75;developed.hordesWon=2;
const stronger=E.getCozyComputed(developed,shared,world,at);
const damaged=structuredClone(developed);damaged.army.militia-=50;
assert(E.getCozyComputed(damaged,shared,world,at).influence.military<stronger.influence.military);
assert.equal(damaged.hordesWon,2,'Troop losses do not erase historical victories');
console.log('PASS new Express calibration, separate resource rates, unchanged materials/Normal, pinned old worlds, zero baseline and reversible military readiness.');
const {hordeForecast}=loadCozyEngine('horde-forecast'),horde=fresh.nextHorde;
assert(horde);
const arrival=horde.arrivesAt,twoDays=fresh.dayMs*2;
assert.equal(hordeForecast(fresh,arrival-twoDays-1).urgent,false);
assert.equal(hordeForecast(fresh,arrival-twoDays).urgent,true);
const sufficient={...fresh,defensePower:horde.power-horde.supportPower};
assert.equal(hordeForecast(sufficient,arrival-1).urgent,false);
assert.equal(hordeForecast(sufficient,arrival-1).gap,0,'Equal power suffices in the actual horde formula');
assert.equal(hordeForecast({...fresh,nextHorde:null},arrival).urgent,false);
console.log('PASS horde warning starts two world days before arrival only when unprepared, counts ally support once, accepts equal defense and stops after the last wave.');
