import assert from 'node:assert/strict';
import {loadCozyEngine} from './lib/load-cozy-engine.mjs';
const P=loadCozyEngine('order-presentation');
const old={id:'old',kind:'research',createdAt:0,arrivesAt:600,research:'economy'};
const queued={...old,id:'next',arrivesAt:900,planned:{startsAt:600,expectedLevel:2,cost:{gold:85},started:false}};
assert.equal(P.orderProgress(queued,500),0,'Queue time is never displayed as completed research');
assert.equal(P.orderProgress(queued,700),0,'Unconfirmed scheduled work stays queued until authoritative start');
const started={...queued,planned:{...queued.planned,started:true}};
assert.equal(P.orderProgress(started,750),50,'Progress uses actual planned start, not original payment time');
assert.equal(P.orderProgress(old,450),75,'Legacy order progress stays unchanged');
assert.equal(P.orderExpectedLevel(queued,0),2,'Queued level belongs to its own planned transition');
assert.equal(P.orderExpectedLevel(old,4),4);
assert.deepEqual(P.orderSummary([old,queued]),{active:1,queued:1,label:'1 ativa · 1 na fila'});
assert.equal(P.orderSummary([]).label,'Sem ordens');assert.equal(P.orderSummary([queued]).active,0);
assert.equal(P.orderMapLabel({...old,kind:'attack',targetPlayerId:'other'}),'Ataque a outro império');
assert.equal(P.orderMapLabel({...old,kind:'attack',returning:true}),'Retorno do exército');
assert.equal(P.orderMapLabel({...old,kind:'attack',sanctuaryPactId:'tower'}),'Desafio aos guardiões');
assert.equal(P.orderMapLabel({...old,kind:'attack'}),'Ataque ao NPC');
console.log('PASS queue presentation: future progress, authoritative start, legacy timing, expected levels and active/queued counts');
