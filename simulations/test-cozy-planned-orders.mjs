import assert from 'node:assert/strict';
import {loadCozyEngine} from './lib/load-cozy-engine.mjs';
const E=loadCozyEngine(),C=loadCozyEngine('city-crisis'),START=1800000000000,DAY=86400000;
const w={id:'plans',name:'Plans',mode:'express',economyVersion:2,speedMultiplier:1,status:'running',startsAt:START,influenceVersion:2};
const fresh=()=>{const x=E.settleCozyState(E.createCozyState(w,'p','p',START),E.createCozyShared(w),w,START);x.state.resources={gold:1e6,materials:1e6,supplies:1e6};return x;};
const act=(x,a,t=START)=>E.applyCozyAction(x.state,x.shared,w,a,t);
let x=fresh();const original=structuredClone(x),city=x.state.cities[0];
x=act(x,{type:'plan_upgrade',cityId:city.id,sector:'economy',steps:4});assert.deepEqual(original,fresh());
assert.equal(x.state.orders.length,4);assert.equal(x.state.orders.filter(o=>o.planned.started).length,1);
const spent=original.state.resources.materials-x.state.resources.materials;assert(spent>0);
const end=Math.max(...x.state.orders.map(o=>o.arrivesAt));
const bulk=E.settleCozyState(x.state,x.shared,w,end+DAY);
let staged=x;for(const at of [...x.state.orders.map(o=>o.arrivesAt),end+DAY])staged=E.settleCozyState(staged.state,staged.shared,w,at);
assert.equal(bulk.state.cities[0].sectors.economy,original.state.cities[0].sectors.economy+4);assert.deepEqual(bulk.state.resources,staged.state.resources);assert.deepEqual(bulk.state.progression,staged.state.progression);
const canceled=act(x,{type:'cancel_plan',orderId:x.state.orders[1].id});assert.equal(canceled.state.orders.length,1);assert(canceled.state.resources.materials>x.state.resources.materials);
assert.throws(()=>act(canceled,{type:'cancel_plan',orderId:x.state.orders[1].id}));assert.throws(()=>act(x,{type:'cancel_plan',orderId:x.state.orders[0].id}));
const poor=fresh();poor.state.resources.materials=500;const before=structuredClone(poor);assert.throws(()=>act(poor,{type:'plan_upgrade',cityId:city.id,sector:'economy',steps:4}));assert.deepEqual(poor,before);
let research=fresh();research=act(research,{type:'plan_research',research:'economy',steps:4});const last=research.state.orders.at(-1).arrivesAt;research=E.settleCozyState(research.state,research.shared,w,last);assert.equal(research.state.research.economy,4);
let lost=fresh();const colony={...structuredClone(lost.state.cities[0]),id:'colony',capital:false,q:lost.state.cities[0].q+5,r:lost.state.cities[0].r+5};lost.state.cities.push(colony);lost.shared.claims[`${colony.q},${colony.r}`]={playerId:'p',cityId:colony.id,name:colony.name};lost=act(lost,{type:'plan_upgrade',cityId:colony.id,sector:'economy',steps:3});const refund=lost.state.orders.filter(o=>!o.planned.started).reduce((s,o)=>s+o.planned.cost.materials,0),m=lost.state.resources.materials;assert(C.releaseCity(lost.state,lost.shared,colony,START,'separation'));assert.equal(lost.state.resources.materials,m+refund);assert.equal(lost.state.orders.length,0);
console.log('PASS plans: prepaid levels, automatic offline starts, staged equality, cascade cancellation, no double refund, atomic insufficient funds, research and city loss');

let capacity=fresh();const capCity=capacity.state.cities[0];
for(const sector of ['economy','administration','society'])capacity=act(capacity,{type:'plan_upgrade',cityId:capCity.id,sector,steps:4});
capacity=act(capacity,{type:'plan_upgrade',cityId:capCity.id,sector:'defense',steps:1});
assert.equal(capacity.state.orders.filter(o=>o.planned&&!o.planned.started).length,12);
assert.throws(()=>act(capacity,{type:'plan_upgrade',cityId:capCity.id,sector:'defense',steps:1}),/12 planos/);
const legacyWorld={...w,economyVersion:undefined};let legacy=E.settleCozyState(E.createCozyState(legacyWorld,'l','l',START),E.createCozyShared(legacyWorld),legacyWorld,START);legacy.state.resources.gold=1e6;
legacy=E.applyCozyAction(legacy.state,legacy.shared,legacyWorld,{type:'plan_research',research:'economy',steps:4},START);
legacy=E.applyCozyAction(legacy.state,legacy.shared,legacyWorld,{type:'plan_research',research:'economy',steps:1},START);
assert.throws(()=>E.applyCozyAction(legacy.state,legacy.shared,legacyWorld,{type:'plan_research',research:'military',steps:1},START),/4 planos/);
console.log('PASS modern capacity 12 and historical capacity 4 remain bounded');

const {researchQueueQuote}=loadCozyEngine('order-presentation');
let mixed=act(fresh(),{type:'research',research:'military'});
let quote=researchQueueQuote(mixed.state,'military',DAY,START);
assert.equal(quote.level,1);
assert.equal(quote.startsAt,mixed.state.orders[0].arrivesAt);
const goldBefore=mixed.state.resources.gold;
mixed=act(mixed,{type:'plan_research',research:'military'});
assert.equal(mixed.state.resources.gold,goldBefore-quote.cost);
assert.equal(mixed.state.orders.at(-1).arrivesAt,quote.arrivesAt);
quote=researchQueueQuote(mixed.state,'economy',DAY,START);
mixed=act(mixed,{type:'plan_research',research:'economy'});
assert.equal(mixed.state.orders.at(-1).arrivesAt,quote.arrivesAt);
mixed=E.settleCozyState(mixed.state,mixed.shared,w,quote.arrivesAt);
assert.equal(mixed.state.orders.length,0);
assert.equal(mixed.state.research.military,2);
assert.equal(mixed.state.research.economy,1);
console.log('PASS projected research quotes match charged cost and completion across branches');

{
 const {cityWorksPreview}=loadCozyEngine('city-works');
 const world={...w,persistent:true,economyVersion:3};
 const original=E.createCozyState(world,'batch','Batch',START);
 const shared=E.createCozyShared(world);
 const city=original.cities[0];
 const action={type:'plan_city_works',cityId:city.id};
 const manual=E.applyCozyAction(original,shared,world,{type:'upgrade',cityId:city.id,sector:'defense'},START);
 const dayMs=E.getCozyComputed(manual.state,manual.shared,world,START).dayMs;
 const quote=cityWorksPreview(manual.state,city,dayMs,START);
 assert.equal(quote.works.length,4);
 const send=(works,state=manual.state)=>E.applyCozyAction(state,manual.shared,world,{...action,works},START);
 assert.throws(()=>send([{sector:'defense',level:city.sectors.defense}]),/fila mudou/);
 assert.throws(()=>send([quote.works[0],quote.works[0]]),/repetido/);
 assert.throws(()=>send([null]),/inválido/);
 const stale=quote.works.map((work,i)=>i===0?{...work,level:work.level+1}:work);
 assert.throws(()=>send(stale),/fila mudou/);
 const poor=structuredClone(manual.state);
 poor.resources.materials=quote.materials-1;
 const before=structuredClone(poor);
 assert.throws(()=>send(quote.works,poor),/precisa de mais materiais/i);
 assert.deepEqual(poor,before,'A rejected batch reserves nothing');
 assert.throws(()=>E.applyCozyAction(manual.state,manual.shared,{...world,persistent:false},{...action,works:quote.works},START),/Cozy persistente/);
 const queued=send(quote.works);
 const chain=queued.state.orders;
 assert.equal(chain.length,5);
 assert.equal(chain.at(-1).arrivesAt,quote.arrivesAt);
 assert.equal(queued.state.resources.materials,manual.state.resources.materials-quote.materials);
 assert.deepEqual(chain.slice(1).map(o=>o.planned.startsAt),chain.slice(0,-1).map(o=>o.arrivesAt));
 assert.deepEqual(queued.state.cities[0].sectors,manual.state.cities[0].sectors);
 assert.equal(cityWorksPreview(queued.state,city,dayMs,START).works.length,0);
 assert.throws(()=>send(quote.works,queued.state),/fila mudou/);
 const done=E.settleCozyState(queued.state,queued.shared,world,quote.arrivesAt);
 assert.equal(done.state.orders.length,0);
 assert.deepEqual(done.state.cities[0].sectors,Object.fromEntries(Object.entries(city.sectors).map(([sector,level])=>[sector,level+1])));
 const canceled=E.applyCozyAction(queued.state,queued.shared,world,{type:'cancel_plan',orderId:chain[1].id},START);
 assert.deepEqual(canceled.state.orders,[chain[0]]);
 assert.equal(canceled.state.resources.materials,manual.state.resources.materials);
 console.log('PASS batch works: mixed sectors, exact debit and ETA, stale rejection, offline progression and cancellation');
}
