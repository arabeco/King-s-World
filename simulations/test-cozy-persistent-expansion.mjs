import assert from "node:assert/strict";
import { loadCozyEngine } from "./lib/load-cozy-engine.mjs";

const E = loadCozyEngine();
const { areaCells, discoverResourceArea } = loadCozyEngine("areas");
const { TRADE_ROUTE, FRONTIER_RENEWAL_DAYS } = loadCozyEngine("frontier-renewal");
const { orderMapLabel } = loadCozyEngine("order-presentation");
const { cityNotice, councilNotice, reportNotice, isNewNotice } = loadCozyEngine("notices");
const begin = 1_800_000_000_000;
for (const mode of ["classic", "express"]) {
  const world = { id: "frontier-test", mode, status: "running", startsAt: begin,
    economyVersion: 3, influenceVersion: 2, foundingOnboarding: true, persistent: true };
  let now = begin;
  let { state, shared } = E.settleCozyState(E.createCozyState(world, "player", "Afonso", now), E.createCozyShared(world), world, now);
  const action = value => ({ state, shared } = E.applyCozyAction(state, shared, world, value, now));
  const advance = time => {
    now = time;
    ({ state, shared } = E.settleCozyState(state, shared, world, now));
  };
  const computed = () => E.getCozyComputed(state, shared, world, now);
  const tiles = () => E.getCozyTiles(state, shared, world);
  const coord = tile => ({ q: tile.q, r: tile.r });
  action({ type: "king_choose", profileId: "builder", nickname: "Afonso" });
  action({ type: "counselor", slot: 0, counselorId: "helena" });
  action({ type: "counselor", slot: 1, counselorId: "ines" });
  action({ type: "hire", role: "engineer" });
  action({ type: "found_capital", ...coord(tiles()[0]), name: "Vale Verde", heroId: state.heroes[0].id });
  const dayMs = computed().dayMs;
  const trade = computed().tradeRoute;
  assert.equal(state.resources.gold, 150);
  const neighbor = { q: 24, r: -24 };
  const rival = discoverResourceArea(shared, neighbor, {
    id: "rival-deposit", resource: "gold", capacity: 350, remaining: 350, surveys: 3, contributors: ["rival"],
  }, true);
  rival.owners = ["rival"];
  shared.territories = { ...shared.territories, ...Object.fromEntries(rival.cells.map(key => [key, "rival"])) };
  const initialSupplies = state.resources.supplies;
  const plan = (from,actionValue,at=now)=>E.applyCozyAction(from.state,from.shared,world,actionValue,at);
  const starting = {state,shared};
  assert.throws(()=>plan(starting,{type:"trade_route",trips:4}),/uma a três/);
  const short = structuredClone(starting);
  short.state.resources.supplies = 3*TRADE_ROUTE.supplies-1;
  assert.throws(()=>plan(short,{type:"trade_route",trips:3}),/mais alimento/);
  const bundle = plan(starting,{type:"trade_route",trips:3});
  const queued = bundle.state.orders.filter(order=>order.tradeRoute);
  const interval = (TRADE_ROUTE.travelDays+TRADE_ROUTE.cooldownDays)*dayMs;
  assert.equal(bundle.state.resources.supplies,initialSupplies-3*TRADE_ROUTE.supplies);
  assert.equal(bundle.state.resources.gold,state.resources.gold);
  assert.deepEqual(queued.map(order=>order.arrivesAt),[0,1,2].map(i=>now+i*interval+trade.durationMs));
  assert.deepEqual(queued.map(order=>order.planned?.started),[undefined,false,false]);
  const firstReturn = E.settleCozyState(bundle.state,bundle.shared,world,queued[0].arrivesAt);
  assert.equal(firstReturn.state.resources.gold,state.resources.gold+TRADE_ROUTE.gold);
  assert.throws(()=>plan(firstReturn,{type:"trade_route",trips:1},queued[0].arrivesAt),/viagem ou em descanso/);
  const secondDeparture = E.settleCozyState(firstReturn.state,firstReturn.shared,world,now+interval);
  assert.equal(secondDeparture.state.orders.find(order=>order.id===queued[1].id).planned.started,true);
  assert.throws(()=>plan(secondDeparture,{type:"cancel_plan",orderId:queued[1].id},now+interval),/ainda não começaram/);
  const cancellation = plan(bundle,{type:"cancel_plan",orderId:queued[1].id});
  assert.equal(cancellation.state.resources.supplies,initialSupplies-TRADE_ROUTE.supplies);
  assert.equal(cancellation.state.nextTradeAt,now+interval);
  assert.deepEqual(cancellation.state.orders.filter(order=>order.tradeRoute).map(order=>order.id),[queued[0].id]);
  assert.throws(()=>plan(cancellation,{type:"cancel_plan",orderId:queued[1].id}),/ainda não começaram/);
  const end = queued[2].arrivesAt;
  const bulk = E.settleCozyState(bundle.state,bundle.shared,world,end);
  assert.equal(bulk.state.resources.gold,state.resources.gold+3*TRADE_ROUTE.gold);
  assert.equal(bulk.state.reports.filter(report=>report.title==="Caravana comercial voltou").length,3);
  assert.deepEqual(E.settleCozyState(bulk.state,bulk.shared,world,end),bulk);
  const resumed = E.settleCozyState(secondDeparture.state,secondDeparture.shared,world,end);
  assert.equal(resumed.state.resources.gold,bulk.state.resources.gold);
  assert.equal(resumed.state.resources.supplies,bulk.state.resources.supplies);
  action({ type: "trade_route" });
  assert.equal(state.resources.supplies, initialSupplies - TRADE_ROUTE.supplies);
  const caravan = state.orders.find(order => order.tradeRoute);
  assert.equal(orderMapLabel(caravan), "Caravana comercial");
  assert.equal(caravan.arrivesAt, now + trade.durationMs);
  assert.throws(() => action({ type: "trade_route" }), /viagem ou em descanso/);
  advance(caravan.arrivesAt - 1);
  assert.equal(state.resources.gold, 150);
  advance(caravan.arrivesAt);
  assert.equal(state.resources.gold, 300);
  assert.equal(shared.areas[rival.id].reserve.remaining, 350, "Comércio não toca no estoque do vizinho");
  assert.throws(() => action({ type: "trade_route" }), /viagem ou em descanso/);
  action({ type: "hire", role: "administrator" });
  const newHero = state.heroes[1].id;
  const startTradeAt = state.nextTradeAt;
  // The starting plain district is selected by the same engine that validates the map.
  const options = tiles().filter(tile => !tile.revealed && tile.terrainVisible && tile.distance >= 3 && tile.distance <= 4 && !tile.landmarkId);
  let site;
  for (const tile of options) {
    action({ type: "explore", ...coord(tile) });
    advance(state.orders.find(order => order.kind === "explore").arrivesAt);
    site = tiles().find(cell => cell.foundation?.canFound);
    if (site) break;
  }
  assert(site);
  action({ type: "found_city", ...coord(site), heroId: newHero });
  const foundation = state.orders.find(order => order.foundation);
  assert.equal(state.heroes[1].cityId, null);
  advance(foundation.arrivesAt);
  assert.equal(state.cities.length, 2);
  assert.equal(state.cities[1].heroId, newHero);
  assert.equal(state.heroes[1].cityId, state.cities[1].id);
  const [capital, colony] = state.cities;
  const originalLetter = computed().cityLife[capital.id].decision;
  const secondLetter = computed().cityLife[colony.id].decision;
  assert.equal(originalLetter.author.role, "engineer");
  const mainNotice = cityNotice(originalLetter.id);
  const colonyNotice = cityNotice(secondLetter.id);
  const influenceBeforeReading = computed().influence.total;
  action({ type: "notice_seen", id: mainNotice });
  action({ type: "notice_seen", id: mainNotice });
  assert.equal(computed().influence.total, influenceBeforeReading);
  assert(!isNewNotice(state, mainNotice));
  assert(isNewNotice(state, colonyNotice));
  assert(!state.seenNotices.includes("city:other-reign"));
  action({ type: "notice_seen", id: "city:other-reign" });
  assert(!state.seenNotices.includes("city:other-reign"));
  const reserved = state.heroes[0].id;
  assert.throws(() => action({ type: "assign", heroId: reserved, cityId: null }), /manter as duas cidades/);
  action({ type: "assign", heroId: reserved, cityId: colony.id });
  assert.equal(state.cities[0].heroId,newHero);
  assert.equal(state.cities[1].heroId,reserved);
  assert.deepEqual(computed().cityLife[capital.id].decision.author,originalLetter.author);
  assert.deepEqual(computed().cityLife[colony.id].decision.author,secondLetter.author);
  const audience = computed().decree;
  action({type:"notice_seen",id:councilNotice(audience.id)});
  action({type:"counselor",slot:0,counselorId:"tomas"});
  assert.equal(computed().decree.counselorId,"helena");
  assert(!isNewNotice(state,councilNotice(audience.id)));
  action({type:"decree",decreeId:audience.id,optionId:"listen"});

  // A copy of the realm can advance several game days without changing the live expansion scenario.
  const later = now + 7 * dayMs;
  let review = E.settleCozyState(state,shared,world,later);
  const reviewComputed = () => E.getCozyComputed(review.state,review.shared,world,later);
  const decree = reviewComputed().decree;
  assert.equal(reviewComputed().cityLife[capital.id].decision.id,originalLetter.id);
  assert.equal(decree.counselorId,"tomas");
  assert(decree.suggestedOptionId);
  const sign = optionId => E.applyCozyAction(review.state,review.shared,world,{type:"decree",decreeId:decree.id,optionId},later);
  for (const resource of Object.keys(review.state.resources)) review.state.resources[resource] += 1000;
  const alternative = decree.options.find(option=>option.id!==decree.suggestedOptionId);
  const same = sign(decree.suggestedOptionId), different = sign(alternative.id);
  assert.deepEqual(same.state.decisionInbox.affinity.tomas,[true]);
  assert.deepEqual(different.state.decisionInbox.affinity.tomas,[false]);
  assert.equal(same.state.reports[0].decisionAuthor.id,"tomas");
  const signed = same.state.reports[0];
  const another = same.state.reports[1];
  review = E.applyCozyAction(same.state,same.shared,world,{type:"notice_seen",id:reportNotice(signed.id)},later);
  assert(!isNewNotice(review.state,reportNotice(signed.id)));
  assert(isNewNotice(review.state,reportNotice(another.id)));
  assert(!reviewComputed().decree);
  const choice = reviewComputed().cityLife[capital.id].decision.options[0];
  review = E.applyCozyAction(review.state,review.shared,world,
    {type:"city_decision",cityId:capital.id,decisionId:originalLetter.id,optionId:choice.id},later);
  assert.deepEqual(review.state.reports[0].decisionAuthor,{kind:"hero",...originalLetter.author});
  assert.equal(reviewComputed().cityLife[capital.id].decision,null);
  assert.equal(reviewComputed().cityLife[colony.id].decision.id,secondLetter.id);

  const cities = structuredClone(review);
  const extraSites = tiles().filter(tile=>tile.kind==="plain" && !shared.claims[tile.id]&&!shared.territories[tile.id]).slice(0,8);
  for (const [index,site] of extraSites.entries()) {
    const id = `test-outpost-${index}`, heroId = `test-hero-${index}`;
    cities.state.cities.push({...structuredClone(colony),...coord(site),id,heroId});
    cities.state.heroes.push({id:heroId,role:"administrator",name:`Responsável ${index}`,cityId:id});
    cities.shared.claims[site.id] = {...cities.shared.claims[`${colony.q},${colony.r}`],cityId:id};
  }
  const newDay = later + dayMs;
  const ten = E.settleCozyState(cities.state,cities.shared,world,newDay);
  const tenView = E.getCozyComputed(ten.state,ten.shared,world,newDay);
  const letterIds = Object.values(tenView.cityLife).map(life=>cityNotice(life.decision.id));
  assert.equal(new Set(letterIds).size,10);
  const oneRead = E.applyCozyAction(ten.state,ten.shared,world,{type:"notice_seen",id:letterIds[3]},newDay);
  assert(!isNewNotice(oneRead.state,letterIds[3]));
  assert(letterIds.slice(4).every(id=>isNewNotice(oneRead.state,id)));
  assert.equal(Object.keys(oneRead.state.decisionInbox.cities).length,10);
  advance(Math.max(startTradeAt, now));
  action({ type: "trade_route" });
  const home = state.orders.find(order => order.tradeRoute).arrivesAt;
  advance(home);
  assert(state.resources.gold >= TRADE_ROUTE.gold);
  const reportCount = state.reports.filter(report => report.title === "Caravana comercial voltou").length;
  advance(home);
  assert.equal(state.reports.filter(report => report.title === "Caravana comercial voltou").length, reportCount);

  // Visit a real gold district, then exhaust and renew a single owned reserve.
  const candidates = structuredClone(state);
  candidates.explored = Array.from({ length: 81 }, (_, q) => Array.from({ length: 81 }, (_, r) => `${q - 40},${r - 40}`))
    .flat().filter(key => Math.abs(key.split(",").map(Number).reduce((a, b) => a + b)) <= 40);
  const visible = E.getCozyTiles(candidates, shared, world);
  const gold = visible.find(tile => tile.kind === "gold" && tile.area?.id !== rival.id && !tile.landmarkId &&
    areaCells(tile, true).every(key => !shared.claims[key] && !shared.territories[key]));
  assert(gold);
  const reserveQuest = () => computed().questProgress.find(quest=>quest.id==="defense");
  assert.equal(reserveQuest().target,1);
  assert(!reserveQuest().complete);
  assert.throws(()=>action({type:"quest",questId:"defense"}),/ainda não está pronta/);
  action({ type: "explore", ...coord(gold) });
  advance(state.orders.find(order => order.kind === "explore").arrivesAt);
  assert(!reserveQuest().complete);
  action({ type: "area_annex", ...coord(gold) });
  assert(reserveQuest().complete);
  const conquestsBefore = computed().influence.legacy;
  action({type:"quest",questId:"defense"});
  assert.equal(computed().influence.legacy,conquestsBefore+50);
  assert.match(state.reports[0].body,/Uma reserva do reino/);
  assert.throws(()=>action({type:"quest",questId:"defense"}),/já foi registrada/);
  const id = tiles().find(tile => tile.id === gold.id).area.id;
  shared.areas[id].reserve.remaining = 5;
  action({ type: "collect", ...coord(gold) });
  const emptied = now;
  assert.equal(shared.areas[id].reserve.remaining, 0);
  const collection = state.orders.find(order => order.kind === "collect");
  advance(collection.arrivesAt);
  advance(emptied + FRONTIER_RENEWAL_DAYS * dayMs - 1);
  assert.equal(shared.areas[id].reserve.remaining, 0);
  advance(emptied + FRONTIER_RENEWAL_DAYS * dayMs);
  assert.equal(shared.areas[id].reserve.remaining, shared.areas[id].reserve.capacity);
  assert.deepEqual(shared.areas[id].owners, ["player"]);
  assert.equal(shared.territories[gold.id], "player");

  // Fight a wild camp and verify the return and renewal. A defeated abandoned city stays open to occupation.
  const camp = visible.find(tile => tile.kind === "npc" && !shared.territories[tile.id]);
  const village = visible.find(tile => tile.kind === "abandoned" && !shared.territories[tile.id]);
  assert(camp && village);
  action({ type: "explore", ...coord(camp) });
  advance(state.orders.find(order => order.kind === "explore").arrivesAt);
  assert.equal(tiles().find(tile=>tile.id===camp.id).occupation,undefined);
  state.army.militia = camp.power + 10;
  assert.throws(()=>action({type:"annex",...coord(camp),heroId:state.heroes[0].id}),/saquear o acampamento/);
  assert.equal(computed().influenceDetails.military.victories.count,0);
  action({ type: "attack", ...coord(camp) });
  const attack = state.orders.find(order => order.kind === "attack");
  const lost = structuredClone(state);
  lost.army.militia = 1;
  const repelled = E.settleCozyState(lost,shared,world,attack.arrivesAt);
  assert.equal(repelled.state.progression.feats.frontier.victories.length,0);
  assert(repelled.state.orders.find(order=>order.returning));
  const contested = structuredClone(shared);
  contested.npcResistance ??= {};
  contested.npcResistance[camp.id] = {initial:camp.power,remaining:0,at:attack.arrivesAt-1};
  const tooLate = E.settleCozyState(state,contested,world,attack.arrivesAt);
  assert.equal(tooLate.state.progression.feats.frontier.victories.length,0);
  assert.deepEqual(tooLate.state.army,state.army);
  assert.equal(tooLate.state.orders.find(order=>order.returning)?.cargo,undefined);
  assert(tooLate.state.reports.some(report=>report.title==="Alvo já vencido"));
  const beforeBattle = state.resources.gold;
  advance(attack.arrivesAt);
  assert.equal(shared.npcResistance[camp.id].remaining, 0);
  assert.deepEqual(computed().influenceDetails.military.victories,{count:1,target:6,points:33,max:200});
  assert.equal(tiles().find(tile=>tile.id===camp.id).campRecoveryAt,attack.arrivesAt + FRONTIER_RENEWAL_DAYS * dayMs);
  assert.equal(state.resources.gold, beforeBattle);
  const returning = state.orders.find(order => order.returning);
  advance(returning.arrivesAt);
  assert.equal(state.resources.gold, beforeBattle + returning.cargo.gold);
  assert.throws(()=>action({type:"attack",...coord(camp)}),/ainda está se recuperando/);
  shared.npcResistance[village.id] = { initial: village.power, remaining: 0, at: attack.arrivesAt };
  advance(attack.arrivesAt + FRONTIER_RENEWAL_DAYS * dayMs);
  assert.equal(shared.npcResistance[camp.id], undefined);
  assert.equal(shared.npcResistance[village.id].remaining, 0);
  const winAt = target => {
    if (!state.explored.includes(target.id)) {
      action({type:"explore",...coord(target)});
      advance(state.orders.find(order=>order.kind==="explore").arrivesAt);
    }
    state.army.militia = Math.max(2000,target.power+10);
    action({type:"attack",...coord(target)});
    advance(state.orders.find(order=>order.kind==="attack"&&!order.returning).arrivesAt);
    const homeOrder = state.orders.find(order=>order.returning);
    assert(homeOrder?.cargo?.gold>0);
    advance(homeOrder.arrivesAt);
  };
  winAt(camp);
  assert.equal(computed().influenceDetails.military.victories.count,1,"Acampamento renovado volta a dar saque");
  const moreTargets = visible.filter(tile => tile.id!==camp.id && ['npc','abandoned'].includes(tile.kind) &&
    tile.id!==village.id && !shared.claims[tile.id] && !shared.territories[tile.id]).sort((a,b)=>a.distance-b.distance);
  assert(moreTargets.length>=6);
  state.resources.supplies += 10000;
  for (const target of moreTargets.slice(0,6)) winAt(target);
  const military = computed().influenceDetails.military;
  assert.deepEqual(military.victories,{count:6,target:6,points:200,max:200});
  assert.equal(computed().influence.military,military.readiness+military.victories.points);
  const existing = structuredClone(state);
  delete existing.progression.feats.frontier;
  existing.hordesWon = 6;
  const migrated = E.settleCozyState(existing,shared,world,now);
  assert.equal(migrated.state.progression.feats.frontier.victories.length,6);
  assert(migrated.state.progression.feats.frontier.resourceAreaClaimed);
  console.log(`PASS ${mode}: expansão, cartas, primeira reserva, vitórias distintas e caravanas com fila, retorno e estorno.`);
}
