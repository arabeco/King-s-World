// Read-only check of the deployed Supabase REST boundary. Never prints credentials.
import assert from 'node:assert/strict';
import {writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import nextEnv from '@next/env';
import {createClient} from '@supabase/supabase-js';
const root=fileURLToPath(new URL('..',import.meta.url));
nextEnv.loadEnvConfig(root,false,{info(){},error(){}});
const url=process.env.NEXT_PUBLIC_SUPABASE_URL;
assert.equal(new URL(url).hostname,'wdmrdovkkrgzalnpqdxe.supabase.co','Wrong Supabase project; refusing to query');
const publicKey=process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY||process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
const serverKey=process.env.SUPABASE_SERVICE_ROLE_KEY||process.env.SUPABASE_SECRET_KEY;
assert(publicKey&&serverKey&&publicKey!==serverKey,'Distinct public and server credentials are required locally');
const options={auth:{persistSession:false,autoRefreshToken:false},global:{fetch:(input,init)=>fetch(input,{...init,signal:AbortSignal.timeout(20000)})}};
const client=createClient(url,publicKey,options),server=createClient(url,serverKey,options);
const nobody='00000000-0000-4000-8000-000000000000';
const account=await server.rpc('kw_cozy_account',{p_user_id:nobody});
assert.equal(account.error,null,`Server RPC failed: ${account.error?.code}`);
assert.equal(account.data.account.xp,0);assert.equal(account.data.account.level,1);
const read=await server.from('kw_cozy_world_states').select('world_id').limit(1);
assert.equal(read.error,null,`Server read failed: ${read.error?.code}`);
const forbiddenRead=await client.from('kw_cozy_world_states').select('world_id').limit(1);
const forbiddenRpc=await client.rpc('kw_cozy_account',{p_user_id:nobody});
assert.equal(forbiddenRead.error?.code,'42501','Public snapshot read must be denied by database grants');
assert.equal(forbiddenRpc.error?.code,'42501','Public reward/account RPC must be denied by database grants');
const result={status:'PASS',scope:'Real Supabase REST, read-only; no browser login, match creation or deploy',project:'wdmrdovkkrgzalnpqdxe',checks:['server RPC and PostgREST schema available','server snapshot read permitted','public snapshot read denied','public account RPC denied'],at:new Date().toISOString()};
await mkdir(new URL('../reports/cozy/',import.meta.url),{recursive:true});
await writeFile(new URL('../reports/cozy/remote-http.json',import.meta.url),JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
